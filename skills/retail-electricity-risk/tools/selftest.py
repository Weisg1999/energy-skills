def close(name, actual, expected, tol):
    if abs(actual - expected) > tol:
        raise AssertionError(f"{name}: {actual} != {expected} (tol {tol})")
    print(f"ok  {name:<46} {actual:,.4f}")


def check(condition, name):
    if not condition:
        raise AssertionError(name)
    print(f"ok  {name}")


def raises(callable_, name):
    try:
        callable_()
    except ValueError:
        print(f"ok  {name}")
        return
    raise AssertionError(f"{name}: expected ValueError")


SPOT = curves.base_spot_average()
CUSTOMERS = curves.customers()[:3]
LT_SHARE = 0.7
LT_PRICE = 0.40
DEV = 0.008
OPEX = 0.025

# A. Fixed-price package build-up.
procurement = portfolio.portfolio_margin(CUSTOMERS, LT_SHARE, LT_PRICE, SPOT, DEV, OPEX)["procurement_price"]
quote = package.fixed_price(procurement, DEV, OPEX, 0.010)
close("A fixed quote (CNY/kWh)", quote, 0.46025, 1e-9)
result_a = package.annual_result(0.46, 30e6, procurement, DEV, OPEX)
close("A annual net at 0.46 (CNY)", result_a["net"], 292_500.0, 1e-6)
close("A per-kWh margin at 0.46", result_a["per_kwh"], 0.00975, 1e-12)

# B. Portfolio baseline.
base = portfolio.portfolio_margin(CUSTOMERS, LT_SHARE, LT_PRICE, SPOT, DEV, OPEX)
close("B energy (kWh)", base["energy_kwh"], 60e6, 1e-6)
close("B revenue (CNY)", base["revenue"], 28_900_000.0, 1e-6)
close("B procurement price", base["procurement_price"], 0.41725, 1e-12)
close("B energy cost (CNY)", base["energy_cost"], 25_035_000.0, 1e-3)
close("B net (CNY)", base["net"], 1_885_000.0, 1e-6)
close("B net per kWh", base["per_kwh"], 0.0314166666666665, 1e-12)
close("B gross spread", base["gross_spread"], 0.0644166666666666, 1e-12)

# C. Spot price stress.
stress_120 = portfolio.stress_spot(CUSTOMERS, 1.2, LT_SHARE, LT_PRICE, SPOT, DEV, OPEX)
close("C +20% spot net (CNY)", stress_120["net"], 238_000.0, 1e-6)
stress_130 = portfolio.stress_spot(CUSTOMERS, 1.3, LT_SHARE, LT_PRICE, SPOT, DEV, OPEX)
close("C +30% spot net (CNY)", stress_130["net"], -585_500.0, 1e-6)
be_mult = portfolio.break_even_spot_multiplier(CUSTOMERS, LT_SHARE, LT_PRICE, SPOT, DEV, OPEX)
close("C break-even spot multiplier", be_mult, 1.2289010321797196, 1e-12)
close("C break-even rise percent", (be_mult - 1.0) * 100.0, 22.89010321797196, 1e-10)

# D. Keep/drop a loss-making customer.
d = portfolio.customer_contribution(curves.customers()[3], LT_SHARE, LT_PRICE, SPOT, DEV, OPEX)
close("D candidate net (CNY)", d["net"], -101_250.0, 1e-6)
with_d = portfolio.portfolio_margin(curves.customers(), LT_SHARE, LT_PRICE, SPOT, DEV, OPEX)
close("D portfolio with candidate (CNY)", with_d["net"], 1_783_750.0, 1e-6)
close("D improvement after drop (CNY)", base["net"] - with_d["net"], 101_250.0, 1e-6)

# E. Forecast-deviation exposure.
for sigma, exp_kwh, exp_cost in (
    (0.02, 701.1320197427416, 105.16980296141124),
    (0.04, 14611.926831121753, 2191.789024668263),
    (0.06, 33829.425049236306, 5074.413757385446),
):
    risk = deviation.deviation_risk(1e6, sigma, 0.05, 0.15)
    close(f"E sigma {sigma:.0%} expected excess (kWh)", risk["expected_excess_kwh"], exp_kwh, 1e-6)
    close(f"E sigma {sigma:.0%} expected cost (CNY)", risk["expected_cost"], exp_cost, 1e-6)
risk_4 = deviation.deviation_risk(1e6, 0.04, 0.05, 0.15)
close("E 95% quantile excess (kWh)", risk_4["quantile_excess_kwh"], 28398.559381602143, 1e-6)
close("E 95% quantile cost (CNY)", risk_4["quantile_cost"], 4259.783907240321, 1e-6)
risk_2 = deviation.deviation_risk(1e6, 0.02, 0.05, 0.15)
close("E sigma 2% quantile excess (kWh)", risk_2["quantile_excess_kwh"], 0.0, 1e-12)
close("E single-period excess (kWh)", deviation.excess_energy(1.08e6, 1e6, 0.05), 30_000.0, 1e-6)
close("E single-period cost (CNY)", deviation.deviation_cost(1.08e6, 1e6, 0.05, 0.15), 4_500.0, 1e-6)

# F. Performance guarantee: current vs draft.
current = guarantee.current_guarantee(3e9, 5e8)
close("F current guarantee (CNY)", current, 25_000_000.0, 1e-6)
close("F current funding at 1% (CNY)", guarantee.funding_cost(current, 0.01), 250_000.0, 1e-6)
for coeff, amount in ((1.0, 30_000_000.0), (5.0, 150_000_000.0), (10.0, 300_000_000.0)):
    draft = guarantee.draft_guarantee(3e9, coeff)
    close(f"F draft guarantee coeff {coeff:g} (CNY)", draft, amount, 1e-6)
    close(f"F draft funding coeff {coeff:g} (CNY)", guarantee.funding_cost(draft, 0.01), amount * 0.01, 1e-6)

# G. Collateral gap and top-up.
gap = guarantee.collateral_gap(30_000_000.0, 20_000_000.0)
close("G collateral gap (CNY)", gap["gap"], 10_000_000.0, 1e-6)
check(gap["status"] == "shortfall", "G gap status is shortfall")
check(guarantee.collateral_gap(20_000_000.0, 20_000_000.0)["status"] == "ok", "G fully covered status is ok")
close("G gap funding at 1% (CNY)", guarantee.funding_cost(gap["gap"], 0.01), 100_000.0, 1e-6)

# H. Market-linked package and floor.
linked_base = package.market_linked_price(SPOT, 1.0, 0.01, 0.40, 0.55)
close("H linked price at base (CNY/kWh)", linked_base, 0.4675, 1e-12)
linked_low = package.market_linked_price(0.40, 1.0, 0.01, 0.40, 0.55)
close("H linked price at spot 0.40", linked_low, 0.41, 1e-12)
close("H linked margin at base", package.margin(linked_base, base["procurement_price"], DEV, OPEX), 0.01725, 1e-12)
close("H linked margin at spot 0.40", package.margin(linked_low, 0.40, DEV, OPEX), -0.023, 1e-12)
close("H required floor", 0.40 + DEV + OPEX, 0.433, 1e-12)
close("H fixed-contract break-even spot", package.break_even_spot(0.46, LT_PRICE, LT_SHARE, DEV, OPEX), 0.49, 1e-12)
close("H break-even rise over base", (0.49 / SPOT - 1.0) * 100.0, 7.103825136612016, 1e-10)

# Input validation.
raises(lambda: package.fixed_price(-0.1), "reject negative wholesale price")
raises(lambda: package.market_linked_price(0.4, -1.0), "reject negative pass-through")
raises(lambda: portfolio.portfolio_margin([], LT_SHARE, LT_PRICE, SPOT), "reject empty portfolio")
raises(lambda: portfolio.portfolio_margin(CUSTOMERS, 1.2, LT_PRICE, SPOT), "reject share above one")
raises(lambda: deviation.excess_energy(1e6, 0, 0.05), "reject zero forecast")
raises(lambda: deviation.expected_excess(1e6, 0.0, 0.05), "reject zero sigma")
raises(lambda: deviation.excess_quantile(1e6, 0.04, 0.05, 1.0), "reject level one")
raises(lambda: guarantee.draft_guarantee(3e9, 0.5), "reject coefficient below one")
raises(lambda: guarantee.collateral_gap(-1, 0), "reject negative collateral")
raises(lambda: curves.monthly_energy(0), "reject zero annual energy")
raises(lambda: curves.day_shape("unknown"), "reject unknown customer kind")

# Determinism and shape sanity.
check(curves.day_shape("industrial") == curves.day_shape("industrial"), "day shape is deterministic")
close("day shape sums to one", sum(curves.day_shape("commercial")), 1.0, 1e-12)
close("monthly energy sums to annual", sum(curves.monthly_energy(30e6)), 30e6, 1e-6)
close("spot monthly mean equals level", sum(curves.spot_monthly(1.1)) / 12.0, 1.1, 1e-12)
close("period count", len(curves.tou_periods()), 96, 0)

