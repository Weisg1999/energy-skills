"""Self-test for the retail electricity and risk reference implementation.

Run from this directory:

    python selftest.py

or from the repository root:

    python skills/retail-electricity-risk/tools/selftest.py

The assertions encode the worked examples in
skills/retail-electricity-risk/SKILL.md. All customer and price data are
synthetic, generated by ``curves.py``, and are not a forecast for any real
company or province.
"""

