    avc_rows = {row["name"]: row for row in avc["allocations"]}
    close("K AVC PV (Mvar)", avc_rows["pv"]["mvar"], 30.0, 1e-9)
    close("K AVC SVG (Mvar)", avc_rows["svg"]["mvar"], 30.0, 1e-9)
