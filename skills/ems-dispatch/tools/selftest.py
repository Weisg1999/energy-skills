"""Self-test for the EMS dispatch reference implementation.

Run from this directory:

    python selftest.py

or from the repository root:

    python skills/ems-dispatch/tools/selftest.py

The assertions encode the worked examples in skills/ems-dispatch/SKILL.md and
in the two knowledge drafts. If the text and the code drift apart, this file
fails. All curves are synthetic and generated by ``curves.py``.
"""

from __future__ import annotations

import curves
import dispatch
import market
import microgrid
import storage


def close(name, actual, expected, tol):
    if abs(actual - expected) > tol:
        raise AssertionError(f"{name}: {actual} != {expected} (tol {tol})")
    print(f"ok  {name:<44} {actual:,.4f}")


def check(condition, name):
    if not condition:
        raise AssertionError(name)
    print(f"ok  {name}")


def main():
    # A. Grid-side storage: 100 MW / 200 MWh, 160 MWh usable DC, RTE 88%.
    a = storage.arbitrage_cycle(160, 0.88, 200, 900, 0.03)
    close("A one-way efficiency", a["eta_one_way"], 0.938083, 1e-6)
    close("A discharge (MWh)", a["discharge_mwh"], 150.0933, 1e-3)
    close("A charge (MWh)", a["charge_mwh"], 170.5606, 1e-3)
    close("A gross (CNY/day)", a["gross"], 100_971.86, 0.01)
    close("A degradation (CNY/day)", a["degradation_cost"], 9_619.62, 0.01)
    close("A net energy (CNY/day)", a["net"], 91_352.24, 0.01)

    prices = curves.storage_day_prices()
    run = storage.station_day(
        prices,
        100,
        200,
        0.88,
        soc_min=0.1,
        soc_max=0.9,
        soc_init=0.1,
        dt_h=1.0,
        degradation_per_kwh=0.03,
        states=400,
    )
    check(run["feasible"], "A dispatch is feasible")
    close("A dispatch net revenue (CNY/day)", run["net_revenue"], 91_352.24, 1.0)
    close(
        "A dispatch charge (MWh)",
        sum(run["schedule"]["p_charge_mw"]),
        170.5606,
        0.01,
    )
    close(
        "A dispatch discharge (MWh)",
        sum(run["schedule"]["p_discharge_mw"]),
        150.0933,
        0.01,
    )
    close("A dispatch throughput (MWh)", run["throughput_mwh"], 320.6539, 0.01)
    check(
        all(
            abs(ch * dis) < 1e-9
            for ch, dis in zip(
                run["schedule"]["p_charge_mw"],
                run["schedule"]["p_discharge_mw"],
            )
        ),
        "A no simultaneous charge and discharge",
    )
    check(
        all(0.1 - 1e-9 <= soc <= 0.9 + 1e-9 for soc in run["schedule"]["soc"]),
        "A SOC stays inside the 10%-90% window",
    )

    cap = market.capacity_payment(100, 165, 2, 6)
    close("A capacity ratio", cap["ratio"], 1 / 3, 1e-12)
    close("A capacity payment (CNY/day)", cap["daily"], 15_068.49, 0.01)
    close(
        "A 4h capacity payment (CNY/day)",
        market.capacity_payment(100, 165, 4, 6)["daily"],
        30_136.99,
        0.01,
    )
    close(
        "A 95% availability (CNY/day)",
        market.capacity_payment(100, 165, 2, 6, availability=0.95)["daily"],
        14_315.07,
        0.01,
    )
    close(
        "A total with capacity (CNY/day)",
        run["net_revenue"] + cap["daily"],
        106_420.73,
        1.0,
    )
    close(
        "A with 0.3 MW auxiliary (CNY/day)",
        run["net_revenue"] + cap["daily"] - 0.3 * 24 * 400,
        103_540.73,
        1.0,
    )

    freq = market.frequency_regulation(10, 10, 24, 1500, 6, 1.5)
    close("A frequency capacity (CNY/day)", freq["capacity_revenue"], 2_400.00, 0.01)
    close("A frequency mileage (CNY/day)", freq["mileage_revenue"], 13_500.00, 0.01)
    close("A frequency total (CNY/day)", freq["total"], 15_900.00, 0.01)

    low_rte = storage.arbitrage_cycle(160, 0.85, 200, 900, 0.03)
    close("A RTE 85% net (CNY/day)", low_rte["net"], 88_420.85, 0.02)

    # B. User side: 5 MW / 10 MWh, 8 MWh usable DC, demand charge.
    b = storage.arbitrage_cycle(8, 0.88, 350, 1050, 0.03)
    close("B charge (MWh)", b["charge_mwh"], 8.5280, 1e-3)
    close("B discharge (MWh)", b["discharge_mwh"], 7.5047, 1e-3)
    close("B net energy (CNY/day)", b["net"], 4_414.11, 0.01)
    close("B charge time at 4 MW (h)", b["charge_mwh"] / 4, 2.1320, 1e-3)
    close("B discharge time at 4 MW (h)", b["discharge_mwh"] / 4, 1.8762, 1e-3)
    demand = market.demand_saving(10_000, 12_000, 8_000, 40)
    close("B demand bill before (CNY/month)", demand["before"]["monthly"], 520_000.00, 0.01)
    close("B demand bill after (CNY/month)", demand["after"]["monthly"], 400_000.00, 0.01)
    close("B demand saving (CNY/month)", demand["monthly"], 120_000.00, 0.01)
    close("B demand saving (CNY/day)", demand["daily"], 4_000.00, 0.01)
    close("B total (CNY/day)", b["net"] + demand["daily"], 8_414.11, 0.01)

    # C. Co-located storage: 20 MW / 40 MWh, 30 MWh curtailed charge.
    c = storage.curtailment_charge(
        30, 0.88, 600, degradation_per_kwh=0.03, usable_dc_mwh=32
    )
    close("C stored DC (MWh)", c["stored_dc_mwh"], 28.1425, 1e-3)
    close("C discharge (MWh)", c["discharge_mwh"], 26.4000, 1e-3)
    close("C net, zero-cost charge (CNY/day)", c["net"], 14_148.00, 0.01)
    close(
        "C net, 150 CNY/MWh charge (CNY/day)",
        storage.curtailment_charge(
            30,
            0.88,
            600,
            degradation_per_kwh=0.03,
            charge_cost_per_mwh=150,
            usable_dc_mwh=32,
        )["net"],
        9_648.00,
        0.01,
    )
    constrained = storage.curtailment_charge(
        30, 0.88, 600, degradation_per_kwh=0.03, usable_dc_mwh=20
    )
    close("C capped stored DC (MWh)", constrained["stored_dc_mwh"], 20.0000, 1e-3)
    check(not constrained["feasible_within_energy"], "C energy overflow is flagged")

    # D. Capability assessment.
    d = storage.capability(
        500, 1000, bms_kw=480, pcc_kw=450, derate=0.95, soh=0.98, soc_min=0.2, soc_max=0.95
    )
    close("D available power (kW)", d["available_power_kw"], 418.95, 1e-6)
    close("D available energy (kWh)", d["available_energy_kwh"], 735.00, 1e-6)
    close("D duration (h)", d["duration_h"], 1.7544, 1e-4)

    # E. Microgrid: 96 points, 500 kW PV, 1 MWh / 500 kW, 900 kW PCC.
    day = curves.microgrid_day()
    base = microgrid.baseline_day(
        day["load_kw"],
        day["pv_kw"],
        day["buy_price"],
        dt_h=day["dt_h"],
        pcc_import_kw=900,
        pcc_export_kw=0,
    )
    check(base["feasible"], "E baseline is feasible")
    close("E baseline cost (CNY/day)", base["cost"], 7_408.72, 0.01)
    close("E baseline peak (kW)", base["peak_import_kw"], 878.54, 0.01)
    close("E baseline import (kWh)", base["imported_kwh"], 9_816.03, 0.01)

    micro = microgrid.microgrid_day(
        day["load_kw"],
        day["pv_kw"],
        day["buy_price"],
        capacity_kwh=1000,
        power_charge_kw=500,
        power_discharge_kw=500,
        pcc_import_kw=840,
        pcc_export_kw=0,
        reserve_up_kw=50,
        reserve_hours=1.0,
        dt_h=day["dt_h"],
        states=200,
    )
    check(micro["feasible"], "E microgrid dispatch is feasible")
    close("E microgrid cost (CNY/day)", micro["cost"], 6_525.12, 0.5)
    close("E microgrid peak (kW)", micro["peak_import_kw"], 838.50, 0.5)
    close("E microgrid throughput (kWh)", micro["throughput_kwh"], 3_086.56, 0.5)
    close("E microgrid cycles", micro["equivalent_cycles"], 1.5433, 1e-3)
    close("E microgrid terminal SOC", micro["terminal_soc"], 0.20, 1e-9)
    close("E microgrid curtailment (kWh)", micro["curtailed_kwh"], 0.0, 1e-9)
    close(
        "E microgrid saving (CNY/day)",
        base["cost"] - micro["cost"],
        883.59,
        0.5,
    )
    close(
        "E microgrid saving (%)",
        (base["cost"] - micro["cost"]) / base["cost"] * 100,
        11.93,
        0.01,
    )

    close(
        "E reserve energy margin (kWh)",
        micro["reserve_up_margin_kwh"],
        -52.6316,
        1e-3,
    )
    check(
        all(
            abs(ch * dis) < 1e-9
            for ch, dis in zip(
                micro["schedule"]["p_charge_kw"],
                micro["schedule"]["p_discharge_kw"],
            )
        ),
        "E no simultaneous charge and discharge",
    )
    check(
        all(0.2 - 1e-9 <= soc <= 0.95 + 1e-9 for soc in micro["schedule"]["soc"]),
        "E SOC stays inside the 20%-95% window",
    )
    balance_error = max(
        abs(
            imp
            - max(
                0.0,
                load + ch - dis - pv,
            )
        )
        for imp, load, ch, dis, pv in zip(
            micro["schedule"]["p_import_kw"],
            day["load_kw"],
            micro["schedule"]["p_charge_kw"],
            micro["schedule"]["p_discharge_kw"],
            day["pv_kw"],
        )
    )
    check(balance_error < 1e-6, "E PCC balance holds at every interval")

    # F. Demand coupling: full-power valley charging can raise the peak.
    demand_before = market.demand_bill(800, base["peak_import_kw"], 40)
    demand_after = market.demand_bill(800, micro["peak_import_kw"], 40)
    close("F baseline demand bill (CNY/month)", demand_before["monthly"], 35_082.99, 0.01)
    close("F dispatch demand bill (CNY/month)", demand_after["monthly"], 32_000.00, 0.01)
    close(
        "F demand saving (CNY/month)",
        demand_before["monthly"] - demand_after["monthly"],
        3_082.99,
        0.01,
    )
    close(
        "F full 500 kW valley charge (CNY/month)",
        market.demand_bill(800, 900, 40)["monthly"],
        36_800.00,
        0.01,
    )
    close(
        "F overrun penalty versus baseline (CNY/month)",
        market.demand_bill(800, 900, 40)["monthly"] - demand_before["monthly"],
        1_717.01,
        0.01,
    )
    close(
        "F charging limit at 400 kW valley load (kW)",
        1.05 * 800 - 400,
        440.00,
        1e-9,
    )

    # G. Microgrid sensitivity numbers cited in the knowledge draft.
    deg = microgrid.microgrid_day(
        day["load_kw"],
        day["pv_kw"],
        day["buy_price"],
        capacity_kwh=1000,
        power_charge_kw=500,
        power_discharge_kw=500,
        pcc_import_kw=840,
        pcc_export_kw=0,
        reserve_up_kw=50,
        reserve_hours=1.0,
        degradation_per_kwh=0.03,
        dt_h=day["dt_h"],
        states=200,
    )
    close("G degradation cost (CNY/day)", deg["cost"], 6_617.72, 0.5)
    close("G degradation leaves schedule unchanged", deg["throughput_kwh"], 3_086.56, 0.5)

    bigger = microgrid.microgrid_day(
        day["load_kw"],
        day["pv_kw"],
        day["buy_price"],
        capacity_kwh=1200,
        power_charge_kw=600,
        power_discharge_kw=600,
        pcc_import_kw=840,
        pcc_export_kw=0,
        reserve_up_kw=50,
        reserve_hours=1.0,
        dt_h=day["dt_h"],
        states=200,
    )
    close("G storage +20% cost (CNY/day)", bigger["cost"], 6_350.61, 0.5)
    close("G storage +20% cycles", bigger["equivalent_cycles"], 1.5358, 1e-3)

    loose = microgrid.microgrid_day(
        day["load_kw"],
        day["pv_kw"],
        day["buy_price"],
        capacity_kwh=1000,
        power_charge_kw=500,
        power_discharge_kw=500,
        pcc_import_kw=900,
        pcc_export_kw=0,
        reserve_up_kw=50,
        reserve_hours=1.0,
        dt_h=day["dt_h"],
        states=200,
    )
    close("G 900 kW import limit cost (CNY/day)", loose["cost"], 6_519.97, 0.5)
    close("G 900 kW import limit peak (kW)", loose["peak_import_kw"], 889.47, 0.01)

    pv_plus = [value * 1.2 for value in day["pv_kw"]]
    sell_35 = [0.35] * len(pv_plus)
    base_pv = microgrid.baseline_day(
        day["load_kw"],
        pv_plus,
        day["buy_price"],
        sell_price=sell_35,
        dt_h=day["dt_h"],
        pcc_import_kw=900,
        pcc_export_kw=500,
    )
    exportable = microgrid.microgrid_day(
        day["load_kw"],
        pv_plus,
        day["buy_price"],
        sell_price=sell_35,
        capacity_kwh=1000,
        power_charge_kw=500,
        power_discharge_kw=500,
        pcc_import_kw=840,
        pcc_export_kw=500,
        reserve_up_kw=50,
        reserve_hours=1.0,
        dt_h=day["dt_h"],
        states=200,
    )
    close("G PV +20% baseline (CNY/day)", base_pv["cost"], 6_853.38, 0.5)
    close("G PV +20% with export (CNY/day)", exportable["cost"], 5_996.19, 0.5)
    close("G PV +20% baseline export (kWh)", base_pv["exported_kwh"], 112.17, 0.5)

    guarded = dispatch.dispatch_day(
        day["buy_price"],
        day["load_kw"],
        day["pv_kw"],
        capacity_kwh=1000,
        power_charge_kw=500,
        power_discharge_kw=500,
        eta_charge=0.95,
        eta_discharge=0.95,
        soc_min=0.26,
        soc_max=0.95,
        soc_init=0.32,
        pcc_import_kw=840,
        pcc_export_kw=0,
        reserve_up_kw=50,
        reserve_hours=1.0,
        dt_h=day["dt_h"],
        states=200,
        enforce_reserve_energy=True,
    )
    check(guarded["feasible"], "G reserve-energy dispatch is feasible")
    close("G reserve-energy cost (CNY/day)", guarded["cost"], 6_663.52, 0.5)
    close("G reserve-energy throughput (kWh)", guarded["throughput_kwh"], 2_625.45, 0.5)

    # H. Island energy check.
    island = microgrid.island_energy_need([100.0] * 4, 0.25)
    close("H island energy need (kWh)", island, 100.00, 1e-9)
    check(
        microgrid.island_feasible(120, island, reserve_ratio=0.1)["feasible"],
        "H island energy is sufficient with a 10% reserve",
    )
    check(
        not microgrid.island_feasible(105, island, reserve_ratio=0.1)["feasible"],
        "H island energy shortfall is flagged",
    )

    # I. Determinism and no-storage dispatch equivalence.
    again = storage.station_day(
        prices,
        100,
        200,
        0.88,
        soc_min=0.1,
        soc_max=0.9,
        soc_init=0.1,
        dt_h=1.0,
        degradation_per_kwh=0.03,
        states=400,
    )
    close("I repeat run cost (CNY/day)", again["cost"], run["cost"], 1e-9)
    zero = dispatch.dispatch_day(
        [0.5] * 4,
        [0.0] * 4,
        [0.0] * 4,
        capacity_kwh=100,
        power_charge_kw=0,
        power_discharge_kw=0,
        soc_min=0.1,
        soc_max=0.9,
        soc_init=0.5,
        dt_h=1.0,
        states=20,
    )
    close("I zero-power storage cost (CNY)", zero["cost"], 0.0, 1e-9)

    print("\nAll EMS dispatch self-tests passed.")


if __name__ == "__main__":
    main()
