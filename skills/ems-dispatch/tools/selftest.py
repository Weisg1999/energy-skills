    check(with_st["feasible"], "J storage loop is feasible")
    close("J storage residual shortfall (MWh)", with_st["residual_shortfall_mwh"], 0.1024, 1e-3)
    close("J storage rt cost (CNY)", with_st["rt_cost"], 61.43, 0.5)
